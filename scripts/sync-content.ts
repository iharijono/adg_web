#!/usr/bin/env node
/**
 * Content sync script (Phase 1 — "ci-copy" strategy).
 *
 * Copies markdown content from the two sibling source-of-truth repos into
 * this repo's `content/` directory at build time:
 *
 *   ../adg_prod                -> product one-pager bodies (content/products/)
 *   ../ai-decision-governance  -> public developer/integration docs (content/docs/)
 *
 * Also generates `data/products.ts` from adg_prod's Product Definition
 * Layer export (`../adg_prod/product/generated/domains.json`, itself
 * generated from `adg_prod/domains/*.yaml` by
 * `adg_prod/tools/generate_product_catalog.py`) — see generateProductsTs()
 * below. Product naming/taglines/buyers/capabilities are owned by that
 * YAML, not by this repo.
 *
 * This repo does NOT hand-edit anything under content/ or data/products.ts
 * — both are entirely regenerated by this script. Re-run before every
 * `next build` (wired into `npm run prebuild` and the build-and-push.yml
 * CI workflow).
 */

