function resetDir(dir: string) {
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
}

function copyWithFrontmatter(
  srcAbsPath: string,
  destAbsPath: string,
  extraFrontmatter: Record<string, string>,
) {
  if (!existsSync(srcAbsPath)) {
    throw new Error(`sync-content: source file not found: ${srcAbsPath}`);
  }
  const body = readFileSync(srcAbsPath, "utf-8");
  const frontmatterLines = Object.entries(extraFrontmatter)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join("\n");
  const out = `---\n${frontmatterLines}\n---\n\n${body}`;
  writeFileSync(destAbsPath, out, "utf-8");
}

function syncProducts() {
  const destDir = join(REPO_ROOT, "content", "products");
  resetDir(destDir);
  for (const [slug, relPath] of Object.entries(PRODUCT_SOURCES)) {
    const src = join(ADG_PROD, relPath);
    const dest = join(destDir, `${slug}.md`);
    copyWithFrontmatter(src, dest, {
      slug,
      source: `adg_prod/${relPath}`,
    });
    console.log(`  product  ${slug.padEnd(32)} <- ${relPath}`);
  }
}

function syncBundles() {
  const destDir = join(REPO_ROOT, "content", "bundles");
  resetDir(destDir);
  for (const [slug, relPath] of Object.entries(BUNDLE_SOURCES)) {
    const src = join(ADG_PROD, relPath);
    const dest = join(destDir, `${slug}.md`);
    copyWithFrontmatter(src, dest, {
      slug,
      source: `adg_prod/${relPath}`,
    });
    console.log(`  bundle   ${slug.padEnd(32)} <- ${relPath}`);
  }
}

function syncDocs() {
  const destDir = join(REPO_ROOT, "content", "docs");
  resetDir(destDir);
  for (const [slug, relPath] of Object.entries(DOC_SOURCES)) {
    const src = join(ADG_PLATFORM, relPath);
    const dest = join(destDir, `${slug}.md`);
    copyWithFrontmatter(src, dest, {
      slug,
      source: `ai-decision-governance/${relPath}`,
    });
    console.log(`  doc      ${slug.padEnd(32)} <- ${relPath}`);
  }
}

/** Raw JSON (not markdown) — copied verbatim, no frontmatter wrapping. */
const DATA_SOURCES: Record<string, string> = {
  "decision-tree.json": "product/decision-diagram/decision-tree.json",
};

function syncData() {
  const destDir = join(REPO_ROOT, "content", "data");
  resetDir(destDir);
  for (const [filename, relPath] of Object.entries(DATA_SOURCES)) {
    const src = join(ADG_PROD, relPath);
    if (!existsSync(src)) {
      throw new Error(`sync-content: source file not found: ${src}`);
    }
    const dest = join(destDir, filename);
    writeFileSync(dest, readFileSync(src, "utf-8"), "utf-8");
    console.log(`  data     ${filename.padEnd(32)} <- ${relPath}`);
  }
}

interface SourceCapability {
  id: string;
  name: string;
  status: "available" | "in_development";
}

interface SourceUpgradeSignal {
  signal: string;
  add_domain: string;
}

interface SourceDomain {
  slug: string;
  order: number;
  name: string;
  status: "live" | "meta";
  icon: string;
  color: string;
  tagline: string;
  buyers: string[];
  capabilities: SourceCapability[];
  standalone_sufficient_when?: string[];
  upgrade_signals?: SourceUpgradeSignal[];
}

/**
 * Generates data/products.ts from adg_prod's Product Definition Layer
 * (domains/*.yaml, exported as product/generated/domains.json by
 * `adg_prod/tools/generate_product_catalog.py`).
 *
 * This REPLACES the file that used to be hand-maintained here — the
 * single source of truth for product naming/taglines/buyers/capabilities
 * is now adg_prod/domains/*.yaml. Do not hand-edit data/products.ts;
 * edit the source YAML in adg_prod and re-run `npm run sync-content`.
 */
function generateProductsTs() {
  const domainsJsonPath = join(
    ADG_PROD,
    "product",
    "generated",
    "domains.json",
  );
  if (!existsSync(domainsJsonPath)) {
    throw new Error(
      `sync-content: ${domainsJsonPath} not found. Run ` +
        `'python3 tools/generate_product_catalog.py' in adg_prod first ` +
        `(it generates this file from domains/*.yaml).`,
    );
  }
  const parsed = JSON.parse(readFileSync(domainsJsonPath, "utf-8")) as {
    domains: SourceDomain[];
  };
  const domains = [...parsed.domains].sort((a, b) => a.order - b.order);

  const header = `/**
 * GENERATED FILE — do not hand-edit.
 *
 * Generated by scripts/sync-content.ts from adg_prod's Product Definition
 * Layer (../adg_prod/domains/*.yaml -> product/generated/domains.json).
 * To change product naming, taglines, buyers, or capabilities, edit the
 * YAML in adg_prod and re-run \`npm run sync-content\` (wired into
 * \`npm run prebuild\`).
 *
 * This file is committed to git (like content/data/decision-tree.json)
 * so that a fresh clone's \`npm run dev\` works without first checking out
 * adg_prod — it is regenerated on every build regardless.
 */

export type ProductStatus = "live" | "meta";

/** Named accent used for icon badges/borders across product cards and pages. */
export type ProductColor =
  | "blue"
  | "cyan"
  | "emerald"
  | "violet"
  | "amber"
  | "rose"
  | "indigo";

export type CapabilityStatus = "available" | "in_development";

export interface ProductCapability {
  id: string;
  name: string;
  status: CapabilityStatus;
}

export interface ProductUpgradeSignal {
  signal: string;
  addDomain: string;
}

export interface Product {
  slug: string;
  name: string;
  /** Short one-line value proposition shown on cards. */
  tagline: string;
  /** "live" = standalone product; "meta" = composes other products (Executive Intelligence). */
  status: ProductStatus;
  /** Lucide icon name, rendered dynamically — keep in sync with lucide-react exports. */
  icon: string;
  /** Accent color for this product's icon badge/borders, distinct per product for scannability. */
  color: ProductColor;
  /** Buyer personas this product is pitched to, from adg_prod/internal/product-summary.md. */
  buyers: string[];
  /** Capability bullets with ship status, sourced from the product's customer one-pager. */
  capabilities: ProductCapability[];
  /** Scenarios where this domain alone is enough -- anti-oversell framing, see adg_prod/README.md. */
  standaloneSufficientWhen?: string[];
  /** Signals suggesting another domain should be added, each pointing at that domain's slug. */
  upgradeSignals?: ProductUpgradeSignal[];
}
`;

  const entries = domains
    .map((d) => {
      const caps = d.capabilities
        .map(
          (c) =>
            `      { id: ${JSON.stringify(c.id)}, name: ${JSON.stringify(c.name)}, status: ${JSON.stringify(c.status)} },`,
        )
        .join("\n");
      const standaloneField = d.standalone_sufficient_when
        ? `    standaloneSufficientWhen: ${JSON.stringify(d.standalone_sufficient_when)},\n`
        : "";
      const upgradeField = d.upgrade_signals
        ? `    upgradeSignals: [\n${d.upgrade_signals
            .map(
              (s) =>
                `      { signal: ${JSON.stringify(s.signal)}, addDomain: ${JSON.stringify(s.add_domain)} },`,
            )
            .join("\n")}\n    ],\n`
        : "";
      return `  {
    slug: ${JSON.stringify(d.slug)},
    name: ${JSON.stringify(d.name)},
    tagline: ${JSON.stringify(d.tagline)},
    status: ${JSON.stringify(d.status)},
    icon: ${JSON.stringify(d.icon)},
    color: ${JSON.stringify(d.color)},
    buyers: ${JSON.stringify(d.buyers)},
    capabilities: [
${caps}
    ],
${standaloneField}${upgradeField}  },`;
    })
    .join("\n");

  const footer = `
export function getProduct(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}
`;

  const out = `${header}\nexport const products: Product[] = [\n${entries}\n];\n${footer}`;
  const destPath = join(REPO_ROOT, "data", "products.ts");
  writeFileSync(destPath, out, "utf-8");
  console.log(
    `  generate data/products.ts <- adg_prod/product/generated/domains.json (${domains.length} products)`,
  );
}

interface SourceBundle {
  slug: string;
  name: string;
  pricing_status: "unbundled" | "bundled";
  tagline: string;
  target_industries: string[];
  includes_domains: string[];
}

/**
 * Generates data/bundles.ts from adg_prod's Product Definition Layer bundle
 * export (`product/generated/products.json`, from `products/*.yaml` via
 * `adg_prod/tools/generate_product_catalog.py`).
 *
 * `pricing_status: "unbundled"` bundles compose domains that are each
 * already live and enableable today via the Customer Portal -- what does
 * NOT exist yet is a discounted bundle-level price/SKU for that exact
 * combination. See adg_prod/products/README.md and
 * adg_prod/product/bundles-overview.md for why that distinction exists
 * and must never be blurred on the website.
 */
function generateBundlesTs() {
  const productsJsonPath = join(
    ADG_PROD,
    "product",
    "generated",
    "products.json",
  );
  if (!existsSync(productsJsonPath)) {
    throw new Error(
      `sync-content: ${productsJsonPath} not found. Run ` +
        `'python3 tools/generate_product_catalog.py' in adg_prod first ` +
        `(it generates this file from products/*.yaml).`,
    );
  }
  const parsed = JSON.parse(readFileSync(productsJsonPath, "utf-8")) as {
    products: SourceBundle[];
  };
  const bundles = parsed.products;

  const header = `/**
 * GENERATED FILE — do not hand-edit.
 *
 * Generated by scripts/sync-content.ts from adg_prod's Product Definition
 * Layer (../adg_prod/products/*.yaml -> product/generated/products.json).
 * To change bundle naming, taglines, industries, or domain composition,
 * edit the YAML in adg_prod and re-run \`npm run sync-content\` (wired
 * into \`npm run prebuild\`).
 *
 * \`pricing_status: "unbundled"\` means the domains are already live and
 * enableable today -- there is simply no discounted bundle-level price
 * for this exact combination yet. Never render an "unbundled" bundle as
 * if a bundle discount/SKU exists. See adg_prod/products/README.md and
 * content/bundles/bundles-overview.md.
 */

export type BundlePricingStatus = "unbundled" | "bundled";

export interface Bundle {
  slug: string;
  name: string;
  /** "unbundled" = domains enabled individually, no bundle price yet; "bundled" = a bundle-level price/SKU exists. */
  pricingStatus: BundlePricingStatus;
  tagline: string;
  targetIndustries: string[];
  /** Domain slugs this bundle composes -- each must match a Product['slug'] in data/products.ts. */
  includesDomains: string[];
}
`;

  const entries = bundles
    .map(
      (b) => `  {
    slug: ${JSON.stringify(b.slug)},
    name: ${JSON.stringify(b.name)},
    pricingStatus: ${JSON.stringify(b.pricing_status)},
    tagline: ${JSON.stringify(b.tagline)},
    targetIndustries: ${JSON.stringify(b.target_industries)},
    includesDomains: ${JSON.stringify(b.includes_domains)},
  },`,
    )
    .join("\n");

  const footer = `
export function getBundle(slug: string): Bundle | undefined {
  return bundles.find((b) => b.slug === slug);
}
`;

  const out = `${header}\nexport const bundles: Bundle[] = [\n${entries}\n];\n${footer}`;
  const destPath = join(REPO_ROOT, "data", "bundles.ts");
  writeFileSync(destPath, out, "utf-8");
  console.log(
    `  generate data/bundles.ts <- adg_prod/product/generated/products.json (${bundles.length} bundles)`,
  );
}

function main() {
  console.log(`Syncing content from:`);
  console.log(`  adg_prod:               ${ADG_PROD}`);
  console.log(`  ai-decision-governance: ${ADG_PLATFORM}`);
  console.log();

  if (!existsSync(ADG_PROD)) {
    throw new Error(
      `sync-content: adg_prod not found at ${ADG_PROD}. Checkout it as a sibling directory, or set ADG_PROD_PATH.`,
    );
  }
  if (!existsSync(ADG_PLATFORM)) {
    throw new Error(
      `sync-content: ai-decision-governance not found at ${ADG_PLATFORM}. Checkout it as a sibling directory, or set ADG_PLATFORM_PATH.`,
    );
  }

  syncProducts();
  syncBundles();
  syncDocs();
  syncData();
  generateProductsTs();
  generateBundlesTs();

  console.log("\nContent sync complete.");
}

main();
